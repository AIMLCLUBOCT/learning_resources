"""
### Logistic Regression

Logistic Regression typically creates a linear decision boundary when working with the original features. However, the data points generated by `make_moons()` follow a nonlinear pattern, making it difficult to separate the two classes using a straight line.

To handle this, I used `PolynomialFeatures(degree=2)`, a class from Scikit-learn that generates additional polynomial and interaction features. This allows Logistic Regression to learn a linear decision boundary in the transformed feature space.

During visualization, the decision boundary appears curved in the original two-dimensional feature space, allowing the model to capture the nonlinear pattern of the dataset more effectively.

## Decision Tree
Decision Tree creates axis-aligned splits using feature-based conditions.
These splits form rectangular regions that represent different predicted classes.

## Random Forest:
Random Forest combines predictions from multiple Decision Trees.
It also creates axis-aligned decision regions, but the final boundary
depends on the combined predictions of all the trees.
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.datasets import make_moons
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score
from sklearn.preprocessing import PolynomialFeatures
X, y = make_moons(
    n_samples=2000,
    noise=0.25,
    random_state=42
)
df= pd.DataFrame(X,columns=["Feature 1","Feature 2"])
Y= pd.DataFrame(y,columns=["target"])
df_transformed= pd.DataFrame(np.concatenate((X,Y),axis=1),columns=["Feature 1","Feature 2","Target"])
print(df_transformed)
sns.pairplot(
    df_transformed,
    vars=["Feature 1", "Feature 2"],
    hue="Target"
)
print(plt.show())

#Train_test_split
X_train,X_test,y_train,y_test= train_test_split(df_transformed.drop(columns=['Target']),df_transformed['Target'],test_size=0.2,random_state=42)
print(X_train.shape,y_train.shape)
print(X_test.shape,y_test.shape)

#Logistics Regression
trf1= ColumnTransformer([
    ('trf1',StandardScaler(),slice(0,2))
])
trf2= PolynomialFeatures(degree=2)
trf3= StandardScaler()
trf4= LogisticRegression()
pipe=Pipeline([('trf1',trf1),('trf2',trf2),('trf3',trf3),('trf4',trf4)])
pipe.fit(X_train,y_train)

#DecisionTree
model= DecisionTreeClassifier(max_depth=4)
model.fit(X_train,y_train)

#RandomForest
model1=RandomForestClassifier(random_state=42,n_estimators=50)
model1.fit(X_train,y_train)

#Testing logistic regression model
y_pred=pipe.predict(X_test)
accuracy= accuracy_score(y_test,y_pred)
print("LogisticsRegression::",accuracy*100)

#Testing decision tree
y_pred_decision= model.predict(X_test)
accuracy1= accuracy_score(y_test,y_pred_decision)
print("DecisionTree::",accuracy1*100)

#RandomForest
y_pred_random= model1.predict(X_test)
accuracy2= accuracy_score(y_test,y_pred_random)
print("RandomForest::",accuracy2*100)

#DECISION BOUNDARIES OF THESE MODELS

# Extract feature values
X = df_transformed.drop(columns=["Target"])
y = df_transformed["Target"]

# Create a mesh grid
x_min, x_max = X.iloc[:, 0].min() - 1, X.iloc[:, 0].max() + 1
y_min, y_max = X.iloc[:, 1].min() - 1, X.iloc[:, 1].max() + 1

xx, yy = np.meshgrid(
    np.arange(x_min, x_max, 0.02),
    np.arange(y_min, y_max, 0.02)
)

# Convert mesh grid into a 2D array
grid = np.c_[xx.ravel(), yy.ravel()]

# Predict using all three trained models
Z_logistic = pipe.predict(grid)
Z_tree = model.predict(grid)
Z_forest = model1.predict(grid)

# Reshape predictions to match mesh grid
Z_logistic = Z_logistic.reshape(xx.shape)
Z_tree = Z_tree.reshape(xx.shape)
Z_forest = Z_forest.reshape(xx.shape)

# Create three subplots
fig, axes = plt.subplots(1, 3, figsize=(18, 5))

# Logistic Regression
axes[0].contourf(xx, yy, Z_logistic, alpha=0.3, cmap="coolwarm")
axes[0].scatter(X.iloc[:, 0], X.iloc[:, 1], c=y, cmap="coolwarm", edgecolors="black")
axes[0].set_title("Logistic Regression")

# Decision Tree
axes[1].contourf(xx, yy, Z_tree, alpha=0.3, cmap="coolwarm")
axes[1].scatter(X.iloc[:, 0], X.iloc[:, 1], c=y, cmap="coolwarm", edgecolors="black")
axes[1].set_title("Decision Tree")

# Random Forest
axes[2].contourf(xx, yy, Z_forest, alpha=0.3, cmap="coolwarm")
axes[2].scatter(X.iloc[:, 0], X.iloc[:, 1], c=y, cmap="coolwarm", edgecolors="black")
axes[2].set_title("Random Forest")

# Add labels
for ax in axes:
    ax.set_xlabel("Feature 1")
    ax.set_ylabel("Feature 2")

plt.tight_layout()
plt.savefig("decision_boundary.png", dpi=300, bbox_inches="tight")
plt.show()